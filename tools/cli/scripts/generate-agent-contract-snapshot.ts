// Writes platform/contracts/src/agent-contract-snapshot.ts from the served tool manifest
// (`pnpm --filter @openrhen/cli contract-snapshot`; run `manifest` first if the registry changed).
// Refuses to record changed tools under an unchanged AGENT_CONTRACT_VERSION: bump it first.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  AGENT_CONTRACT_SNAPSHOT,
  MCP_TOOL_MANIFEST,
  agentContractSnapshot,
  extensionContractSnapshotTools
} from "@openrhen/contracts";

const target = fileURLToPath(new URL("../../../platform/contracts/src/agent-contract-snapshot.ts", import.meta.url));
const next = agentContractSnapshot(MCP_TOOL_MANIFEST);
const previous = AGENT_CONTRACT_SNAPSHOT;
if (previous.version === next.version && JSON.stringify(previous.tools) !== JSON.stringify(next.tools)) {
  console.error(
    `The served tools changed but AGENT_CONTRACT_VERSION is still ${next.version}. Bump it in ` +
      "platform/contracts/src/agent-contract.ts, then run this again."
  );
  process.exit(1);
}
// Tools an extension adds are recorded by the extension, not here.
const extensionTools = new Set(Object.keys(extensionContractSnapshotTools()));
const core = {
  ...next,
  tools: Object.fromEntries(Object.entries(next.tools).filter(([name]) => !extensionTools.has(name)))
};
const source = `import type { AgentContractSnapshot } from "./agent-contract.js";

// Generated by \`pnpm --filter @openrhen/cli contract-snapshot\`; do not edit by hand. Records the contract
// version and each served tool's required arguments, so a test can tell when they change without a version bump.
export const CORE_AGENT_CONTRACT_SNAPSHOT: AgentContractSnapshot = ${JSON.stringify(core, null, 2)};
`;
const options = (await resolveConfig(target)) ?? {};
writeFileSync(target, await format(source, { ...options, filepath: target }));
