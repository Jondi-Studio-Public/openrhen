// Writes platform/contracts/src/mcp-manifest-data.ts from the CLI registry (`pnpm --filter @openrhen/cli manifest`).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { buildRemoteManifest } from "../src/remote-manifest.js";
import { loadDropInsFromDisk } from "../src/drop-ins-disk.js";
import { commands } from "../src/registry.js";
import { manifestSource } from "../src/manifest-source.js";
import { commandModules, withoutCommandModules } from "../src/command-modules.js";

await loadDropInsFromDisk();

const target = fileURLToPath(new URL("../../../platform/contracts/src/mcp-manifest-data.ts", import.meta.url));
// The tools of a command module that names a `manifestFile` go to that excluded file, which registers them through the
// contracts extension seam, so the core manifest is complete without them.
const moduleFiles = commandModules().filter((module) => module.manifestFile !== undefined);
// The core manifest is built with those modules unregistered, so it is exactly what the OpenRhen export (which has
// none of them) builds; the full pass adds their tools and the changed core entries to the excluded files.
const hiddenCommands = new Set(moduleFiles.flatMap((module) => module.commands));
const coreManifest = withoutCommandModules(
  moduleFiles.map((module) => module.id),
  () => buildRemoteManifest(commands.filter((command) => !hiddenCommands.has(command)))
);
const manifest = buildRemoteManifest(commands);
const ownedBy = (tool: { command: string }) =>
  moduleFiles.find((module) => module.commands.some((command) => command.name === tool.command));
const coreTools = coreManifest;
const coreByName = new Map(coreManifest.map((tool) => [tool.name, tool]));
// A core tool whose entry differs once a module is loaded (the Inbox tools list the module's rooms).
const changedCore = manifest.filter(
  (tool) => ownedBy(tool) === undefined && JSON.stringify(coreByName.get(tool.name)) !== JSON.stringify(tool)
);
const source = `import type { McpToolManifestEntry } from "./mcp-manifest.js";

// Generated by \`pnpm --filter @openrhen/cli manifest\` from the tools/cli registry; do not edit by hand.
export const MCP_TOOL_MANIFEST_DATA: McpToolManifestEntry[] = ${JSON.stringify(coreTools, null, 2)};
`;
const options = (await resolveConfig(target)) ?? {};
writeFileSync(target, await format(source, { ...options, filepath: target }));

for (const module of moduleFiles) {
  const { file, exportName, overridesName } = module.manifestFile!;
  const tools = manifest.filter((tool) => ownedBy(tool) === module);
  if (tools.length === 0) continue;
  const privateTarget = fileURLToPath(new URL(`../../../platform/contracts/src/private/${file}`, import.meta.url));
  const moduleTools = manifestSource(tools);
  const changed = overridesName === undefined ? undefined : manifestSource(changedCore);
  const usesCommonParams = moduleTools.usesCommonParams || changed?.usesCommonParams === true;
  const privateSource = `${usesCommonParams ? 'import { MCP_COMMON_PARAMS } from "../mcp-common-params.js";\n' : ""}import type { McpToolManifestEntry } from "../mcp-manifest.js";

// Generated by \`pnpm --filter @openrhen/cli manifest\` from the ${module.id} command module; do not edit by hand.
// The shared write-parameter texts are not copied: they refer to MCP_COMMON_PARAMS, so core can reword them.
export const ${exportName}: McpToolManifestEntry[] = ${moduleTools.source};
${
  changed === undefined
    ? ""
    : `
// The core tools whose entry changes once this module is loaded; they replace the core entry of the same name.
export const ${overridesName}: McpToolManifestEntry[] = ${changed.source};
`
}`;
  writeFileSync(privateTarget, await format(privateSource, { ...options, filepath: privateTarget }));
}
