import { endRecurrenceGoalCommandSchema, saveCommitmentRecurrenceRuleCommandSchema } from "@openrhen/contracts";
import type { CommandContext, CommandSpec, ParsedArgs } from "../command.js";
import { requirePositional, stringOption } from "../command.js";
import { CliError, EXIT } from "../errors.js";
import { newEntityId } from "../recurrence-ids.js";
import { asRecords, resolveReference } from "../resolve.js";
import {
  mergeAssignments,
  newCommandId,
  parseAssignments,
  postCommand,
  printOutcome,
  readJsonFile,
  versionOf
} from "../write.js";

/**
 * The fields `saveCommitmentRecurrenceRuleCommandSchema` knows about; everything else (e.g. `version`)
 * is dropped. `repeat` is the discriminated union from `@openrhen/contracts`'s `commitmentRepeatSchema`
 * — either `{ unit: "days", intervalDays: N }` or `{ unit: "months", intervalMonths: N, anchor }`
 * — and `pickRuleFields` copies it whole, the same way it already copies any other nested field verbatim.
 * `--set repeat.unit=days --set repeat.intervalDays=7` or `--set repeat.unit=months --set
 * repeat.intervalMonths=1 --set repeat.anchor=last_day` or `--set repeat.unit=weeks --set
 * repeat.intervalWeeks=1 --set repeat.weekdays=[2,4]` (a JSON array, 0=Sunday..6=Saturday) builds it via `parseAssignments`/
 * `mergeAssignments`'s dotted-key nesting (`../write.js`), exactly as `recurrence.intervalDays=1`
 * already does for an action's own recurrence.
 */
const RULE_FIELDS = [
  "id",
  "title",
  "timezone",
  "startDate",
  "endDate",
  "repeat",
  "localStartTime",
  "localEndTime",
  "location",
  "locationId",
  "setupBeforeMinutes",
  "transitionAfterMinutes",
  "presence",
  "status",
  "projectId",
  "contactId",
  "shareToCalendar",
  "private",
  // The travel time model design note: `latenessMatters` is a boolean (absent = leave as stored); `transportMode`
  // is car, bike or walk, and `--set transportMode=null` clears it back to "usual".
  "latenessMatters",
  "transportMode"
] as const;

function pickRuleFields(record: Record<string, unknown>): Record<string, unknown> {
  const rule: Record<string, unknown> = {};
  for (const field of RULE_FIELDS) if (record[field] !== undefined) rule[field] = record[field];
  return rule;
}

/** The rule fields whose value differs between the stored rule and the one about to be saved. */
function changedRuleFields(
  before: Record<string, unknown> | undefined,
  after: Record<string, unknown>
): Record<string, { from: unknown; to: unknown }> {
  const changed: Record<string, { from: unknown; to: unknown }> = {};
  for (const field of RULE_FIELDS) {
    const from = before?.[field];
    const to = after[field];
    if (JSON.stringify(from) !== JSON.stringify(to)) changed[field] = { from: from ?? null, to: to ?? null };
  }
  return changed;
}

async function runSet(context: CommandContext, args: ParsedArgs): Promise<void> {
  const fromPath = stringOption(args.values, "from");
  const base = fromPath ? readJsonFile(fromPath) : {};
  const overlay = mergeAssignments(base, parseAssignments(args.values, "set"));
  // Omitting an id creates a new rule, same as the portal's own editor never asking a human for one.
  const id =
    stringOption(args.values, "id") ?? (typeof overlay.id === "string" ? overlay.id : undefined) ?? newEntityId();

  const state = await context.client.getState();
  const existing = asRecords(state.commitmentRecurrenceRules).find((rule) => rule.id === id);
  const rule = pickRuleFields(mergeAssignments(existing ?? {}, { ...overlay, id }));

  const payload: Record<string, unknown> = {
    commandId: newCommandId(),
    expectedVersion: versionOf(existing),
    rule
  };
  const parsed = saveCommitmentRecurrenceRuleCommandSchema.safeParse(payload);
  if (!parsed.success)
    throw new CliError(
      'This recurrence rule does not match the contract. See "rhen guide recurrence" for the three ' +
        "recurrence kinds.",
      EXIT.validation,
      parsed.error.issues
    );

  // --dry-run: show the rule diff and how many stored future commitments belong to the series, which
  // is what the save rewrites. The new occurrences themselves are generated by the portal on save.
  const now = context.now();
  const futureOccurrences = asRecords(state.commitments).filter(
    (commitment) =>
      commitment.recurrenceRuleId === id &&
      commitment.status !== "cancelled" &&
      typeof commitment.startsAt === "string" &&
      new Date(commitment.startsAt) > now
  );
  const preview = {
    creates: existing === undefined,
    changedFields: changedRuleFields(existing, rule),
    futureOccurrencesAffected: futureOccurrences.length,
    ...(futureOccurrences.length > 0
      ? {
          firstAffected: futureOccurrences
            .slice(0, 5)
            .map((commitment) => ({ id: commitment.id, startsAt: commitment.startsAt }))
        }
      : {})
  };

  const result = await postCommand(context, args, {
    path: "/api/commands/commitment-recurrence",
    payload,
    summary: `${existing ? "update" : "create"} the recurrence rule "${id}"`,
    needsYes: "This changes every future occurrence of the series.",
    preview
  });
  if (result.state === null) return;
  printOutcome(context, result.state, {
    stateKey: "commitmentRecurrenceRules",
    id,
    fallback: "Recurrence rule saved.",
    timeZone: state.settings.timezone
  });
}

async function runEnd(context: CommandContext, args: ParsedArgs): Promise<void> {
  const actionQuery = requirePositional(recurrenceCommand, args, 1);
  const state = await context.client.getState();
  const action = resolveReference(state, "actions", actionQuery);
  const actionId = String(action.id);

  const payload: Record<string, unknown> = {
    commandId: newCommandId(),
    expectedVersion: versionOf(action),
    type: "end_recurrence_goal",
    actionId
  };
  const parsed = endRecurrenceGoalCommandSchema.safeParse(payload);
  if (!parsed.success)
    throw new CliError(
      "This end-recurrence-goal command does not match the contract.",
      EXIT.validation,
      parsed.error.issues
    );

  const result = await postCommand(context, args, {
    path: "/api/commands/recurrence-goal",
    payload,
    summary: `end the recurrence goal on ${actionId}`
  });
  if (result.state === null) return;
  printOutcome(context, result.state, {
    stateKey: "actions",
    id: actionId,
    fallback: "Recurrence goal ended.",
    timeZone: state.settings.timezone
  });
}

export const recurrenceCommand: CommandSpec = {
  name: "recurrence",
  summary: "Create, update, or end a recurrence",
  description:
    "`recurrence set` creates or updates a commitment recurrence rule, which rewrites every future occurrence " +
    "of the series and so requires --yes; `recurrence end` ends a recurring action's own goal without " +
    "touching anything else about the action.",
  positionals: [
    { name: "subcommand", required: true, description: "set or end" },
    { name: "target", required: false, description: "end: the action's id or exact title" }
  ],
  options: {
    from: {
      type: "string",
      placeholder: "file.json",
      localPath: true,
      description: "set: a JSON file with the rule's fields"
    },
    set: {
      type: "string",
      placeholder: "key=value",
      multiple: true,
      description: "set: assign one field of the rule, e.g. localEndTime=19:00"
    },
    id: { type: "string", placeholder: "ruleId", description: "set: the rule to update; omit to create" },
    "dry-run": { type: "boolean", description: "Print the command instead of sending it" },
    yes: { type: "boolean", description: "set: confirm rewriting every future occurrence of the series" }
  },
  mutates: true,
  destructive: true,
  examples: [
    'recurrence set --id rule-gym --set "title=Gym v2" --yes',
    "recurrence set --from rule.json --yes",
    "recurrence set --id rule-gym --set latenessMatters=false --set transportMode=bike --yes",
    "recurrence set --id rule-gym --set transportMode=null --yes",
    'recurrence end "Weed the beds"',
    "recurrence set --id rule-gym --set localEndTime=19:00 --yes --dry-run",
    "recurrence set --set repeat.unit=days --set repeat.intervalDays=7 --set title=Gym --set timezone=Europe/London " +
      "--set startDate=2026-09-10 --set localStartTime=07:00 --set localEndTime=08:00 --yes",
    "recurrence set --id rule-gym --set repeat.unit=months --set repeat.intervalMonths=1 " +
      "--set repeat.anchor=day_of_month --yes",
    "recurrence set --id rule-class --set repeat.unit=weeks --set repeat.intervalWeeks=1 " +
      "--set repeat.weekdays=[2,4] --yes"
  ],
  async run(context: CommandContext, args: ParsedArgs) {
    const subcommand = requirePositional(recurrenceCommand, args, 0);
    if (subcommand === "set") return runSet(context, args);
    if (subcommand === "end") return runEnd(context, args);
    throw new CliError(`Unknown recurrence subcommand "${subcommand}". Use "set" or "end".`, EXIT.usage);
  }
};
