#!/usr/bin/env node
// Writes portal/server/mcp-route-table.ts (and server/private/mcp-route-table.ts): one entry per portal/app/api/**/route.ts, each a literal lazy import so the
// bundler follows it. The remote MCP endpoint's in-process runner dispatches the CLI's requests through this table
// and refuses any path that is not in it. Run `pnpm --filter @openrhen/portal routes:table` after adding or
// removing an API route (it formats the result); `server/mcp-route-table.test.ts` fails while the table and the
// route files disagree.
//
// A route file whose first line is `// @drop-in <name>` belongs to the drop-in `drop-ins/<name>/` (see
// `server/drop-ins.ts`). It is left out of the core table and written to `drop-ins/<name>/route-table.ts`, which
// registers it when the folder loads, so the core table names no route whose files may be absent.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { classify, validateManifest } from "../../scripts/extract/extract.mjs";

const portalRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const apiRoot = join(portalRoot, "app", "api");
const target = join(portalRoot, "server", "mcp-route-table.ts");
const privateTarget = join(portalRoot, "server", "private", "mcp-route-table.ts");
const manifest = validateManifest(
  JSON.parse(readFileSync(resolve(portalRoot, "..", "scripts", "extract", "manifest.json"), "utf8"))
);

function routeFiles(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) return routeFiles(path);
    return entry === "route.ts" ? [path] : [];
  });
}

const templateOf = (file) => `/api/${relative(apiRoot, dirname(file)).split(sep).join("/")}`.replace(/\/$/, "");
const dropInOf = (file) => /^\/\/ @drop-in (\S+)\r?\n/.exec(readFileSync(file, "utf8"))?.[1];

const coreTemplates = [];
const dropIns = new Map();
for (const file of routeFiles(apiRoot)) {
  const dropIn = dropInOf(file);
  if (dropIn === undefined) coreTemplates.push(templateOf(file));
  else dropIns.set(dropIn, [...(dropIns.get(dropIn) ?? []), templateOf(file)]);
}
const templates = coreTemplates.sort();
// A route whose file the OpenRhen export excludes goes in the private table, which the export replaces
// with an empty one; the core table then lists exactly the routes the export keeps.
const isPrivate = (template) => classify(`portal/app${template}/route.ts`, manifest) === "excluded";
const entryLines = (list) =>
  [...list]
    .sort()
    .map((template) => `  "${template}": () => import("@/app${template}/route")`)
    .join(",\n");
const entries = entryLines(templates.filter((template) => !isPrivate(template)));
const privateEntries = entryLines(templates.filter(isPrivate));

const source = `// Generated by \`pnpm --filter @openrhen/portal routes:table\`; do not edit by hand.
// One entry per portal/app/api/**/route.ts, keyed by route template, each a literal lazy import so the bundler
// follows it. \`server/mcp-route-table.test.ts\` keeps this and the route files in step.
import { PRIVATE_MCP_ROUTE_TABLE } from "./private/mcp-route-table";

export type RouteHandler = (request: Request, context: never) => Promise<Response> | Response;
export type RouteMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
export type RouteModule = Partial<Record<RouteMethod, RouteHandler>>;

/** Routes the core ships; \`MCP_ROUTE_TABLE\` adds the private ones. */
export const CORE_MCP_ROUTE_TABLE: Record<string, () => Promise<RouteModule>> = {
${entries}
};

/** Adds a drop-in's routes (\`drop-ins/<name>/route-table.ts\`, called when the folder loads). */
export function registerMcpRoutes(routes: Record<string, () => Promise<RouteModule>>): void {
  Object.assign(MCP_ROUTE_TABLE, routes);
}

export const MCP_ROUTE_TABLE: Record<string, () => Promise<RouteModule>> = {
  ...CORE_MCP_ROUTE_TABLE,
  ...PRIVATE_MCP_ROUTE_TABLE
};
`;
const privateSource = `// Generated by \`pnpm --filter @openrhen/portal routes:table\`; do not edit by hand.
// The routes the OpenRhen export leaves out (scripts/extract/manifest.json). The export excludes this directory and
// ships an empty table in its place (extract/overlay/portal/server/private/mcp-route-table.ts).
import type { RouteModule } from "../mcp-route-table";

export const PRIVATE_MCP_ROUTE_TABLE: Record<string, () => Promise<RouteModule>> = {
${privateEntries}
};
`;

mkdirSync(dirname(privateTarget), { recursive: true });
const written = [target, privateTarget];
writeFileSync(target, source);
writeFileSync(privateTarget, privateSource);
for (const [name, list] of dropIns) {
  const dropInTarget = join(portalRoot, "drop-ins", name, "route-table.ts");
  writeFileSync(
    dropInTarget,
    `// Generated by \`pnpm --filter @openrhen/portal routes:table\`; do not edit by hand.
// The routes of the \`${name}\` drop-in, registered with the MCP route table when the folder loads.
import { registerMcpRoutes } from "@/server/mcp-route-table";

registerMcpRoutes({
${entryLines(list)}
});
`
  );
  written.push(dropInTarget);
}
execFileSync("pnpm", ["exec", "prettier", "--write", ...written], { cwd: resolve(portalRoot, ".."), stdio: "inherit" });
console.log(
  `Wrote ${templates.length} routes to ${relative(portalRoot, target)}` +
    [...dropIns].map(([name, list]) => `, ${list.length} to drop-ins/${name}`).join("")
);
